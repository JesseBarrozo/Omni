import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { after, describe, it } from "node:test";

import {
  checkAtlas,
  checkCitations,
  generateAtlas,
  parseEngineRegistry,
  parseEnvExample,
  parseTables,
  projectFromArguments,
  writeAtlas,
} from "../scripts/atlas.mjs";

// Only a project named explicitly is mapped; Omni has no default project.
const repoRoot = projectFromArguments([], process.env);
const projectPresent = Boolean(repoRoot);
const scratch = [];

function fixtureRoot(files) {
  const root = mkdtempSync(join(tmpdir(), "atlas-test-"));
  scratch.push(root);
  for (const [path, content] of Object.entries(files)) {
    const full = join(root, path);
    mkdirSync(join(full, ".."), { recursive: true });
    writeFileSync(full, content);
  }
  return root;
}

after(() => {
  for (const root of scratch) rmSync(root, { recursive: true, force: true });
});

const registrySample = `
  const tasks = createTaskCapabilities(dependencies.access, dependencies.tasks);
  const memories = createMemoryCapabilities(
    dependencies.access,
  );

  return createEngine({
    capabilities: {
      task_lists_create: tasks.task_lists_create,
      knowledge_document_revisions_create:
        knowledge.knowledge_document_revisions_create,
      memories_list: memories.memories_list,
    },
  });
`;

describe("parseEngineRegistry", () => {
  it("reads single-line and wrapped registrations with their group and line", () => {
    const entries = parseEngineRegistry(registrySample);
    assert.deepEqual(
      entries.map(({ id, group, member }) => ({ id, group, member })),
      [
        { id: "task_lists_create", group: "tasks", member: "task_lists_create" },
        {
          id: "knowledge_document_revisions_create",
          group: "knowledge",
          member: "knowledge_document_revisions_create",
        },
        { id: "memories_list", group: "memories", member: "memories_list" },
      ],
    );
    assert.equal(entries[0].line, registrySample.split("\n").findIndex((l) => l.includes("task_lists_create:")) + 1);
  });
});

describe("parseTables", () => {
  it("finds table names with the line where each is declared", () => {
    const source = 'export const a = pgTable(\n  "tasks",\n  {});\nexport const b = pgTable("memories", {});';
    assert.deepEqual(parseTables(source), [
      { name: "tasks", line: 1 },
      { name: "memories", line: 4 },
    ]);
  });
});

describe("parseEnvExample", () => {
  it("keeps the comment above each key and masks secrets", () => {
    const source = [
      "# Public OAuth/MCP origin.",
      "SECOND_BRAIN_PUBLIC_URL=https://brain.example.com",
      "OPENROUTER_API_KEY=change-me",
      "",
    ].join("\n");
    assert.deepEqual(parseEnvExample(source), [
      { key: "SECOND_BRAIN_PUBLIC_URL", value: "https://brain.example.com", description: "Public OAuth/MCP origin.", line: 2 },
      { key: "OPENROUTER_API_KEY", value: "<secret placeholder>", description: "", line: 3 },
    ]);
  });
});

describe("checkCitations", () => {
  it("accepts a citation to an existing line", () => {
    const root = fixtureRoot({ "src/a.ts": "one\ntwo\n", "atlas/page.md": "See `src/a.ts:2`.\n" });
    assert.deepEqual(checkCitations(root, ["atlas/page.md"]), []);
  });

  it("reports a citation to a missing file", () => {
    const root = fixtureRoot({ "atlas/page.md": "See `src/gone.ts:1`.\n" });
    assert.match(checkCitations(root, ["atlas/page.md"])[0], /src\/gone\.ts:1 does not exist/);
  });

  it("reports a citation beyond the end of the file", () => {
    const root = fixtureRoot({ "src/a.ts": "one\n", "atlas/page.md": "See `src/a.ts:9`.\n" });
    assert.match(checkCitations(root, ["atlas/page.md"])[0], /src\/a\.ts:9 is past the end/);
  });
});

describe("ATLAS_PROJECT atlas", { skip: !projectPresent && "set ATLAS_PROJECT to a project root to run" }, () => {
  it("registers capabilities from the engine registry", () => {
    const pages = generateAtlas(repoRoot);
    const index = JSON.parse(pages.get("atlas/index.json"));
    assert.ok(index.capabilities.length > 0);
  });

  it("keeps the generated pages in step with the sources", () => {
    assert.deepEqual(checkAtlas(repoRoot), []);
  });

  it("writes every generated page with a do-not-edit header", () => {
    for (const [path, content] of generateAtlas(repoRoot)) {
      if (path.endsWith(".md")) assert.match(content, /^<!-- generated by tools\/atlas\/generate\.mjs/, path);
    }
  });
});

describe("writeAtlas", () => {
  it("writes the pages so that checkAtlas passes on a fixture", () => {
    const root = fixtureRoot({
      "package.json": JSON.stringify({ name: "x", workspaces: [] }),
      "apps/engine/src/engine.ts": registrySample,
      "apps/engine/src/capabilities/tasks.ts": "export {};\n",
      "apps/engine/src/database/schema/t.ts": 'pgTable("tasks", {});\n',
      ".env.example": "# Key.\nSAMPLE=1\n",
    });
    writeAtlas(root);
    assert.deepEqual(checkAtlas(root), []);
  });
});

describe("projectFromArguments", () => {
  it("has no default project", () => {
    assert.equal(projectFromArguments(["check"], {}), null);
  });

  it("takes the path argument first, then ATLAS_PROJECT", () => {
    assert.equal(projectFromArguments(["check", "/tmp/a"], { ATLAS_PROJECT: "/tmp/b" }), resolve("/tmp/a"));
    assert.equal(projectFromArguments(["check"], { ATLAS_PROJECT: "/tmp/b" }), resolve("/tmp/b"));
  });
});

describe("generic projects", () => {
  const PAGES = ["map.md", "documents.md", "config.md", "external-dependencies.md", "README.md", "index.json"];

  it("maps a project without the engine layout", () => {
    const root = fixtureRoot({
      "pyproject.toml": '[project]\nname = "tool"\n',
      "src/app/main.py": 'import requests\nrequests.get("https://api.service.io/v1")\n',
      "tests/test_main.py": "def test_ok():\n    assert True\n",
      ".env.example": "# Token for the service.\nSERVICE_TOKEN=change-me\n",
      "README.md": "# Tool\n\nDoes things.\n",
    });
    const pages = generateAtlas(root);
    for (const page of PAGES) assert.ok(pages.has(`atlas/${page}`), page);
    assert.equal(pages.has("atlas/capabilities.md"), false);
    const index = JSON.parse(pages.get("atlas/index.json"));
    assert.deepEqual(index.stack, ["python"]);
    assert.ok(index.externalHosts.some((entry) => entry.host === "api.service.io"));
    assert.ok(index.env.some((entry) => entry.key === "SERVICE_TOKEN"));
    assert.equal(index.tests.count, 1);
    assert.equal(index.documents[0].title, "Tool");
  });

  it("maps an empty folder without inventing content", () => {
    const root = fixtureRoot({});
    const index = JSON.parse(generateAtlas(root).get("atlas/index.json"));
    assert.deepEqual(index.stack, []);
    assert.equal(index.sourceFiles, 0);
    assert.equal(index.entryPoints.length, 0);
  });

  it("reads scripts and entry points from package.json with citations", () => {
    const root = fixtureRoot({
      "package.json": '{\n  "name": "web",\n  "bin": { "web": "./bin/web.js" },\n  "scripts": {\n    "start": "node server.js"\n  }\n}\n',
      "bin/web.js": "#!/usr/bin/env node\n",
    });
    const index = JSON.parse(generateAtlas(root).get("atlas/index.json"));
    assert.deepEqual(index.stack, ["node"]);
    assert.deepEqual(index.scripts.map((s) => [s.name, s.line]), [["start", 5]]);
    assert.ok(index.entryPoints.some((e) => e.path === "bin/web.js"));
  });

  it("writes a checkable atlas and removes pages that are no longer produced", () => {
    const root = fixtureRoot({ "pyproject.toml": "[project]\n", "src/main.py": "print(1)\n" });
    writeAtlas(root);
    assert.deepEqual(checkAtlas(root), []);
    writeFileSync(
      join(root, "atlas", "capabilities.md"),
      "<!-- generated by tools/atlas/generate.mjs. Do not edit by hand. Source digest: x -->\n",
    );
    assert.match(checkAtlas(root).join("\n"), /capabilities\.md is obsolete/);
    writeAtlas(root);
    assert.deepEqual(checkAtlas(root), []);
  });
});
