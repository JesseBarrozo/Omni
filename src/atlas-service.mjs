// Atlas of the project open in the harness: status for the GUI and generation
// on request. The generator itself lives in scripts/atlas.mjs.

import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

import { writeAtlas } from "../scripts/atlas.mjs";

const ATLAS_DIR = "atlas";
const INDEX_FILE = "index.json";
const PAGE_NAME = /^[a-z0-9][a-z0-9-]*\.md$/i;
const GENERATED_HEADER = /^<!-- generated by .*-->\n?/;

// The generated index is the marker: the manual README can exist without it.
export function atlasStatus(rootPath) {
  const indexPath = join(rootPath, ATLAS_DIR, INDEX_FILE);
  if (!existsSync(indexPath)) return { present: false, path: ATLAS_DIR };
  const index = JSON.parse(readFileSync(indexPath, "utf8"));
  return {
    present: true,
    path: ATLAS_DIR,
    digest: index.digest,
    stack: index.stack ?? [],
    sourceFiles: index.sourceFiles ?? 0,
    entryPoints: index.entryPoints?.length ?? 0,
    scripts: index.scripts?.length ?? 0,
    documents: index.documents?.length ?? 0,
    externalHosts: new Set((index.externalHosts ?? []).map((site) => site.host)).size,
    capabilities: index.capabilities?.length ?? 0,
    tables: index.tables?.length ?? 0,
  };
}

// Pages the generator wrote, each with its title: the first level-one heading.
export function atlasPages(rootPath) {
  const dir = join(rootPath, ATLAS_DIR);
  if (!existsSync(join(dir, INDEX_FILE))) return [];
  return readdirSync(dir)
    .filter((name) => PAGE_NAME.test(name))
    .sort()
    .map((name) => {
      const text = readFileSync(join(dir, name), "utf8").replace(GENERATED_HEADER, "");
      const title = /^#\s+(.+)$/m.exec(text)?.[1].trim() ?? name;
      return { name, title };
    });
}

// Names are checked against the page pattern, so a request never reaches a
// file outside the atlas folder.
export function readAtlasPage(rootPath, name) {
  const path = join(rootPath, ATLAS_DIR, name);
  if (!PAGE_NAME.test(name) || !existsSync(path)) throw new Error("Page d'atlas inconnue.");
  return readFileSync(path, "utf8").replace(GENERATED_HEADER, "");
}

export function generateAtlas(rootPath) {
  return writeAtlas(rootPath);
}
